package api

import (
	"context"
	"slices"
	"strings"
	"time"
	"unicode/utf8"
	"uuid"

	"gitverse.ru/zagvozdeen/agenda/internal/models"
	"gitverse.ru/zagvozdeen/agenda/internal/models/enums"
)

type AddChecklistItemsInput struct {
	TaskID string   `json:"task_id" jsonschema:"Task to append checklist items to."`
	Items  []string `json:"items" jsonschema:"Nonempty array of plain-text items in their intended order; each must contain 1 to 255 characters. New items are unchecked."`
}

type ChecklistItemInput struct {
	TaskID string    `json:"task_id" jsonschema:"Task containing the checklist item."`
	ItemID uuid.UUID `json:"item_id" jsonschema:"Permanent checklist item ID."`
}

type UpdateChecklistItemInput struct {
	TaskID string    `json:"task_id" jsonschema:"Task containing the checklist item."`
	ItemID uuid.UUID `json:"item_id" jsonschema:"Permanent checklist item ID."`
	Text   *string   `json:"text,omitempty" jsonschema:"New plain text, 1 to 255 characters."`
	Done   *bool     `json:"done,omitempty" jsonschema:"Explicit completion value; repeating the same value does not change the item."`
}

type ReorderChecklistItemsInput struct {
	TaskID  string      `json:"task_id" jsonschema:"Task containing the checklist."`
	ItemIDs []uuid.UUID `json:"item_ids" jsonschema:"All current checklist item IDs exactly once, in the desired order. Use an empty array only for an empty checklist."`
}

type ChecklistResult struct {
	TaskID    string                 `json:"task_id"`
	Checklist []models.ChecklistItem `json:"checklist"`
	UpdatedAt time.Time              `json:"updated_at"`
}

func (a *API) registerChecklist() {
	registerTool(a, "add_checklist_items", "Append one or more plain-text items to a task checklist in one atomic operation. IDs and UTC timestamps are generated by the server. Requires board membership.", false, false, a.AddChecklistItems)
	registerTool(a, "update_checklist_item", "Update a checklist item's text or boolean completion by ID. Completion never changes task status. Requires board membership.", false, false, a.UpdateChecklistItem)
	registerTool(a, "delete_checklist_item", "Remove a checklist item and renumber remaining positions without changing their relative order. Requires board membership.", false, false, a.DeleteChecklistItem)
	registerTool(a, "reorder_checklist_items", "Set checklist order by providing every current item ID exactly once. Completion and creation timestamps are preserved. Requires board membership.", false, false, a.ReorderChecklistItems)
}

func validChecklistText(text string) (string, error) {
	text = strings.TrimSpace(text)
	if text == "" || utf8.RuneCountInString(text) > 255 || strings.ContainsRune(text, '\x00') {
		return "", invalid("checklist text must contain 1 to 255 characters without null characters")
	}
	return text, nil
}

func (a *API) writableChecklist(ctx context.Context, taskID string) (*ChecklistResult, error) {
	task, err := a.writableTask(ctx, taskID)
	if err != nil {
		return nil, err
	}
	items, err := a.store.GetChecklist(ctx, task.ID)
	if err != nil {
		return nil, err
	}
	return &ChecklistResult{TaskID: task.ID, Checklist: items, UpdatedAt: task.UpdatedAt}, nil
}

func (a *API) saveChecklist(ctx context.Context, result *ChecklistResult, before []models.ChecklistItem) (any, error) {
	if slices.Equal(before, result.Checklist) {
		return result, nil
	}
	updatedAt, err := a.store.UpdateChecklist(ctx, result.TaskID, result.Checklist)
	if err != nil {
		return nil, err
	}
	result.UpdatedAt = updatedAt
	if err = a.event(ctx, result.TaskID, enums.EventTypeUpdated, "checklist", before, result.Checklist); err != nil {
		return nil, err
	}
	return result, nil
}

func (a *API) AddChecklistItems(ctx context.Context, input AddChecklistItemsInput) (any, error) {
	if len(input.Items) == 0 {
		return nil, invalid("at least one checklist item must be provided")
	}
	texts := make([]string, len(input.Items))
	for index, text := range input.Items {
		var err error
		texts[index], err = validChecklistText(text)
		if err != nil {
			return nil, err
		}
	}
	result, err := a.writableChecklist(ctx, input.TaskID)
	if err != nil {
		return nil, err
	}
	before := slices.Clone(result.Checklist)
	now := time.Now().UTC()
	for _, text := range texts {
		result.Checklist = append(result.Checklist, models.ChecklistItem{
			ID: uuid.NewV7(), Text: text, Position: len(result.Checklist) + 1,
			CreatedAt: now, UpdatedAt: now,
		})
	}
	return a.saveChecklist(ctx, result, before)
}

func (a *API) UpdateChecklistItem(ctx context.Context, input UpdateChecklistItemInput) (any, error) {
	if input.Text == nil && input.Done == nil {
		return nil, invalid("at least one checklist item field must be provided")
	}
	if input.Text != nil {
		text, err := validChecklistText(*input.Text)
		if err != nil {
			return nil, err
		}
		input.Text = &text
	}
	result, err := a.writableChecklist(ctx, input.TaskID)
	if err != nil {
		return nil, err
	}
	index := slices.IndexFunc(result.Checklist, func(item models.ChecklistItem) bool { return item.ID == input.ItemID })
	if index < 0 {
		return nil, &Error{Code: "not_found", Message: "checklist item not found"}
	}
	before := slices.Clone(result.Checklist)
	item := &result.Checklist[index]
	if input.Text != nil {
		item.Text = *input.Text
	}
	if input.Done != nil {
		item.Done = *input.Done
	}
	if *item != before[index] {
		item.UpdatedAt = time.Now().UTC()
	}
	return a.saveChecklist(ctx, result, before)
}

func (a *API) DeleteChecklistItem(ctx context.Context, input ChecklistItemInput) (any, error) {
	result, err := a.writableChecklist(ctx, input.TaskID)
	if err != nil {
		return nil, err
	}
	index := slices.IndexFunc(result.Checklist, func(item models.ChecklistItem) bool { return item.ID == input.ItemID })
	if index < 0 {
		return nil, &Error{Code: "not_found", Message: "checklist item not found"}
	}
	before := slices.Clone(result.Checklist)
	result.Checklist = slices.Delete(result.Checklist, index, index+1)
	now := time.Now().UTC()
	for index := range result.Checklist {
		if result.Checklist[index].Position != index+1 {
			result.Checklist[index].Position = index + 1
			result.Checklist[index].UpdatedAt = now
		}
	}
	return a.saveChecklist(ctx, result, before)
}

func (a *API) ReorderChecklistItems(ctx context.Context, input ReorderChecklistItemsInput) (any, error) {
	if input.ItemIDs == nil {
		return nil, invalid("item_ids must be an array")
	}
	result, err := a.writableChecklist(ctx, input.TaskID)
	if err != nil {
		return nil, err
	}
	if len(input.ItemIDs) != len(result.Checklist) {
		return nil, conflict("item_ids must contain every current checklist item exactly once; reload the task before retrying")
	}
	items := make(map[uuid.UUID]models.ChecklistItem, len(result.Checklist))
	for _, item := range result.Checklist {
		items[item.ID] = item
	}
	reordered := make([]models.ChecklistItem, len(input.ItemIDs))
	now := time.Now().UTC()
	for index, id := range input.ItemIDs {
		item, ok := items[id]
		if !ok {
			return nil, conflict("item_ids contains a duplicate or unknown checklist item; reload the task before retrying")
		}
		delete(items, id)
		if item.Position != index+1 {
			item.Position = index + 1
			item.UpdatedAt = now
		}
		reordered[index] = item
	}
	before := result.Checklist
	result.Checklist = reordered
	return a.saveChecklist(ctx, result, before)
}
